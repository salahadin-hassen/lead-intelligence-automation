#!/usr/bin/env bash
# Render the form document root from demo/ + deploy/env/form.env.
#
#   var/www/index.html        copy of demo/lead-form.html
#   var/www/lead-form.html    same file under its explicit name
#   var/www/config.js         GENERATED from DEMO_N8N_WEBHOOK_URL
#
# config.js is the single place a deployment configures the webhook URL
# (the committed demo/config.js is only the local development default).
# The rendered copy is never hand-edited and lives under var/ (gitignored).
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ENV_FILE="${FORM_ENV_FILE:-$REPO/deploy/env/form.env}"
WWW_ROOT="${WWW_ROOT:-$REPO/var/www}"

if [ ! -f "$ENV_FILE" ]; then
  echo "render-form: missing $ENV_FILE (cp $ENV_FILE.example $ENV_FILE and edit)" >&2
  exit 1
fi
set -a
# shellcheck disable=SC1090
. "$ENV_FILE"
set +a

if [ -z "${DEMO_N8N_WEBHOOK_URL:-}" ]; then
  echo "render-form: DEMO_N8N_WEBHOOK_URL is empty in $ENV_FILE" >&2
  exit 1
fi

mkdir -p "$WWW_ROOT"
cp "$REPO/demo/lead-form.html" "$WWW_ROOT/lead-form.html"
cp "$REPO/demo/lead-form.html" "$WWW_ROOT/index.html"

# Generate config.js with the URL JSON-escaped (a JS string literal is a
# JSON string literal, so this stays injection-safe for quotes/newlines).
WEBHOOK_JSON="$(python3 -c 'import json, sys; print(json.dumps(sys.argv[1]))' "$DEMO_N8N_WEBHOOK_URL")"
cat > "$WWW_ROOT/config.js" <<EOF
/* Generated by deploy/bin/render-form.sh from $ENV_FILE — do not edit. */
window.LEAD_FORM_CONFIG = {
  webhookUrl: $WEBHOOK_JSON,
};
EOF

echo "render-form: wrote $WWW_ROOT (webhookUrl=$DEMO_N8N_WEBHOOK_URL)"
